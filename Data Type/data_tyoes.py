# Data types in python

# Numeric data types

# 1. int
a = 10
print(type(a))

# 2. float
b = 3.14
print(type(b))


# Sequence data types

# string
c = "Hello, World!"
print(type(c))

# list

my_list = [1, 2, 3, 4, 5]
print(type(my_list))

# tuple
my_tuple = (1, 2, 3, 4, 5)
print(type(my_tuple))

# Boolean data type

# 4. bool
d = True
print(type(d))

# 5. Char
e = "A"
print(type(e))


# set data type
# unique vakues
set = {1, 2, 3, 4, 5}
print(type(set))
