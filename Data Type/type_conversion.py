# Type Conversion in Python

a = 10  # Integer

b = 3.14  # Float

c = "Hello"  # String

# Converting integer to float

to_float = float(a)

print(to_float)  # Output: 10.0

print(type(to_float))


# Converting float to integer

to_integer = int(b)

print(type(to_integer))  # Output: <class 'int'>

print(to_integer)


# Converting Integer to String

to_string = str(a)

print(type(to_string))  # Output: <class 'str'>

print(to_string)

